"""Compile smoke.vert with xsc and write the smoke test's shader header from the tested pixel variants."""
import os, subprocess, sys
from pathlib import Path
# Usage: gen_smoke_header.py <work dir from compile_variants.sh> <output header>; needs XSDK_DIR, and glslang on PATH or in GLSLANG.
S = Path(sys.argv[1]); out = Path(sys.argv[2]); here = Path(__file__).resolve().parent
sys.path.insert(0, str(Path(os.environ['XSDK_DIR'])/'xenos-toolchain'))
import xsc.spirv as spirv, xsc.lower as L
from xasm.program import LIBXENON_REGISTERS as REG

vs = S/'smoke_vs.spv'
subprocess.run([os.environ.get('GLSLANG', 'glslang'), '-G', '--target-env', 'opengl', '--auto-map-bindings', here/'smoke.vert', '-o', vs], check=True, stdout=subprocess.DEVNULL)
items = [('vs', vs), ('ps1', S/'v/v1_tex_modulate.f.spv'), ('ps2', S/'v/v2_lit_fog_alpha.f.spv'),
         ('ps3', S/'v/v3_3stage_8light.f.spv'), ('ps4', S/'v/v4_indirect.f.spv')]
t = ['/* Generated by gen_smoke_header.py from xsc; do not edit. */', 'struct smoke_lit { int reg; float v[4]; };', '']
for name, spv in items:
    blob, man = L.lower_ex(spirv.Module.parse(Path(spv).read_bytes()), REG, True)
    bad = [e for e in man if not isinstance(e[0], int)]
    if bad: sys.exit(f'{name}: unhandled manifest entries {bad}')
    t.append(f'static unsigned char {name}_bin[] __attribute__((aligned(4))) = {{')
    t += ['\t' + ', '.join(f'0x{b:02x}' for b in blob[i:i+12]) + ',' for i in range(0, len(blob), 12)]
    t += ['};', f'static const struct smoke_lit {name}_lit[] = {{']
    t += ['\t{%d, {%sf, %sf, %sf, %sf}},' % (r, *map(repr, map(float, v))) for r, v in man] or ['\t{-1, {0, 0, 0, 0}},']
    t += ['};', f'#define {name.upper()}_NLIT {len(man)}', '']
    print(name, len(blob), 'bytes,', len(man), 'literals')
out.write_text('\n'.join(t))
